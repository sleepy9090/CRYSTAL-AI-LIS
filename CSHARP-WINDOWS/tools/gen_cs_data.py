"""Generate src/ReC.Core/Gen/R.cs from ../web/data/ram_labels.json (../CSHARP/docs/architecture_cs.md §1 rule 2).

Every RAM/WRAM label (labels.csv bank `*`, name -> address) becomes `public const int <PascalName> = 0x....;`
in `static class R` (namespace ReC.Gen). snake_case -> PascalCase, keeping hex-looking parts as written
(tmp_0A -> Tmp0A, obj_x_lo_s01 -> ObjXLoS01). The names of ../web/src/game/ram.js `R` are all in the json.

usage: python3 tools/gen_cs_data.py [--check]   (--check: exit 1 if R.cs is out of date, write nothing)
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, '..', 'web', 'data', 'ram_labels.json')
OUT = os.path.join(ROOT, 'src', 'ReC.Core', 'Gen', 'R.cs')


def pascal(name):
    return ''.join(p[:1].upper() + p[1:] for p in name.split('_') if p)


def render(labels):
    lines = [
        '// <auto-generated> by tools/gen_cs_data.py from ../web/data/ram_labels.json — do not edit. </auto-generated>',
        '// RAM ($0000-$07FF) / WRAM ($6000-$7FFF) addresses by label name (labels.csv bank `*`).',
        'namespace ReC.Gen;',
        '',
        '/// <summary>RAM / WRAM label addresses (= web/data/ram_labels.json; game/ram.js R names are a subset).</summary>',
        'public static class R',
        '{',
    ]
    seen = {}
    for name, addr in sorted(labels.items(), key=lambda kv: (kv[1], kv[0])):
        cs = pascal(name)
        if cs in seen:
            sys.exit(f'name clash: {name} and {seen[cs]} -> {cs}')
        seen[cs] = name
        lines.append(f'    /// <summary>{name}</summary>')
        lines.append(f'    public const int {cs} = 0x{addr:04X};')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def main():
    with open(SRC) as fh:
        labels = json.load(fh)
    text = render(labels)
    if '--check' in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ''
        if cur != text:
            sys.exit('Gen/R.cs is out of date (run python3 tools/gen_cs_data.py)')
        print(f'R.cs up to date ({len(labels)} labels)')
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w') as fh:
        fh.write(text)
    print(f'wrote {os.path.relpath(OUT, ROOT)} ({len(labels)} labels)')


if __name__ == '__main__':
    main()
