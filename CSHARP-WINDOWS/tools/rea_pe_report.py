"""REA inspections of the shipped exe -> docs/rea/ (TASKS.md T6, architecture_win.md §4).

usage: python3 tools/rea_pe_report.py [--exe PATH] [--no-run]
  Runs (rea CLI, --json; each result saved as docs/rea/<name>.json):
    pe_imports        rea inspect-pe-imports dist/ReC.exe
    hardening         rea inspect-binary-hardening dist/ReC.exe
    pe_resources      rea inspect-pe-resources dist/ReC.exe
    exposure          rea audit-release-exposure dist/ReC.exe   (also lists sibling .pdb / .map files in dist/)
    members_core      rea inspect-managed-members <trimmed ReC.Core.dll that went into the bundle> --detail summary
    members_win       rea inspect-managed-members <trimmed ReC.dll (ReC.Win)> --detail summary
  The trimmed assemblies are src/ReC.Win/obj/Release/net10.0-windows/win-x64/linked/ (what the single-file bundle
  holds, compressed). Then writes docs/rea/summary.md: import DLLs, hardening flags, resources, exposure checks,
  member counts, exe size + sha256, and checks the expectations (exit 1 if one fails):
    * imports only from the expected system DLL set (EXPECTED_DLLS),
    * ASLR (dynamic base + high-entropy VA) and DEP (NX compat) on,
    * an icon group, a version resource and a manifest present,
    * no .pdb next to the exe and no build-machine home path in the trimmed assemblies.
  --no-run: rebuild summary.md from the saved JSON only.
"""
import hashlib
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'docs', 'rea')
LINKED = os.path.join(ROOT, 'src', 'ReC.Win', 'obj', 'Release', 'net10.0-windows', 'win-x64', 'linked')
# the .NET single-file host (singlefilehost.exe) imports from these; the managed code reaches user32 / gdi32 /
# winmm / xinput only through P/Invoke at run time, which never shows in the PE import table
EXPECTED_DLLS = {
    'kernel32.dll', 'advapi32.dll', 'user32.dll', 'ole32.dll', 'oleaut32.dll', 'shell32.dll', 'bcrypt.dll',
    'crypt32.dll', 'ncrypt.dll', 'ws2_32.dll', 'version.dll', 'shlwapi.dll', 'gdi32.dll', 'winmm.dll',
}


def rea(args):
    p = subprocess.run(['rea'] + args + ['--json'], stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True,
                       timeout=900)
    try:
        return json.loads(p.stdout)
    except json.JSONDecodeError:
        return {'_error': f'rc {p.returncode}', '_stdout': p.stdout[-2000:], '_stderr': p.stderr[-2000:]}


def runs(exe):
    return {
        'pe_imports': ['inspect-pe-imports', exe],
        'hardening': ['inspect-binary-hardening', exe],
        'pe_resources': ['inspect-pe-resources', exe],
        'exposure': ['audit-release-exposure', exe],
        # full Evidence -> out/ (cs_rea_members.py's default bundles; large, not committed)
        'members_core': ['inspect-managed-members', os.path.join(LINKED, 'ReC.Core.dll'), '--detail', 'summary',
                         '--evidence_output', os.path.join(ROOT, 'out', 'rea_members.json')],
        'members_win': ['inspect-managed-members', os.path.join(LINKED, 'ReC.dll'), '--detail', 'summary',
                        '--evidence_output', os.path.join(ROOT, 'out', 'rea_members_win.json')],
    }


def scrub(v):
    """build-machine paths in the saved JSON -> paths relative to this folder"""
    if isinstance(v, dict):
        return {k: scrub(x) for k, x in v.items()}
    if isinstance(v, list):
        return [scrub(x) for x in v]
    if isinstance(v, str) and ROOT in v:
        return v.replace(ROOT, '.')
    return v


def walk(v, path=''):
    """every (path, scalar) of a JSON value"""
    if isinstance(v, dict):
        for k, x in v.items():
            yield from walk(x, f'{path}.{k}' if path else k)
    elif isinstance(v, list):
        for i, x in enumerate(v):
            yield from walk(x, f'{path}[{i}]')
    else:
        yield path, v


RES_TYPES = {3: 'ICON', 14: 'GROUP_ICON', 16: 'VERSION', 24: 'MANIFEST', 10: 'RCDATA', 6: 'STRING'}


def nr(r):
    return r.get('normalized_result') or {}


def summarize(exe, res):
    lines, fails = [], []

    def check(ok, what):
        lines.append(f'- {"OK" if ok else "**FAIL**"}: {what}')
        if not ok:
            fails.append(what)

    data = open(exe, 'rb').read()
    lines += ['# REA report — dist/ReC.exe', '',
              f'Generated by `python3 tools/rea_pe_report.py` (rea CLI; raw Evidence JSON beside this file).', '',
              f'- size {len(data):,} bytes, sha256 `{hashlib.sha256(data).hexdigest()}`', '']

    imp = nr(res['pe_imports'])
    dlls = sorted({d['name'].lower() for d in imp.get('imports', [])})
    delay = sorted({d['name'].lower() for d in imp.get('delay_imports', [])})
    lines += ['## Imports (inspect-pe-imports)', '',
              f'- {imp.get("coverage", {}).get("imports", "?")} functions from {len(dlls)} DLLs: ' + ', '.join(dlls),
              f'- delay-load: ' + (', '.join(delay) or 'none'),
              '- user32 / gdi32 / winmm / xinput calls of ReC.Win are P/Invokes resolved at run time, not PE imports.']
    unexpected = [d for d in dlls + delay if d not in EXPECTED_DLLS and not d.startswith('api-ms-win-')]
    check(not unexpected, 'only expected system DLLs / api-ms-win-* sets imported'
          + (f' (unexpected: {", ".join(unexpected)})' if unexpected else ''))
    lines.append('')

    rows = {}
    for img in nr(res['hardening']).get('images', []):
        for r in img.get('rows', []):
            rows[r['property']] = r['state']
    lines += ['## Hardening (inspect-binary-hardening)', '']
    lines += [f'- {k}: {v}' for k, v in sorted(rows.items())]
    for k in ('dynamic_base', 'high_entropy_va', 'nx_compat'):
        check(rows.get(k) == 'enabled', f'{k} enabled')
    lines.append('')

    rr = nr(res['pe_resources'])
    types = {}
    for r in rr.get('resources', []):
        t = r['type'].get('id')
        name = r['name'].get('id', r['name'].get('name'))
        types.setdefault(RES_TYPES.get(t, str(t)), []).append(name)
    lines += ['## Resources (inspect-pe-resources)', '']
    lines += [f'- {t}: {", ".join(map(str, v))}' for t, v in sorted(types.items())]
    groups = rr.get('icon_groups', [])
    for g in groups:
        sizes = [im['width'] or 256 for im in g.get('images', [])]
        lines.append(f'- icon group (resource index {g.get("resource_index")}): sizes {sizes}')
    check(bool(groups) and 'GROUP_ICON' in types, 'icon group present (app.ico)')
    check('VERSION' in types, 'version resource present')
    check('MANIFEST' in types, 'application manifest present')
    lines.append('')

    ex = nr(res['exposure'])
    lines += ['## Release exposure (audit-release-exposure)', '',
              f'- summary: {json.dumps(ex.get("summary", {}), sort_keys=True)}']
    for c in ex.get('checks', []):
        if c.get('status') in ('exposed', 'unknown', 'not_assessed'):
            obs = c.get('observation', {}).get('counts', {})
            lines.append(f'- {c["id"]}: {c["status"]}{" (" + c["severity"] + ")" if c.get("severity") else ""} {json.dumps(obs, sort_keys=True)}')
    pdbs = [f for f in os.listdir(os.path.dirname(exe)) if f.lower().endswith(('.pdb', '.map'))]
    check(not pdbs, 'no .pdb / .map beside the exe' + (f' ({", ".join(pdbs)})' if pdbs else ''))
    home = os.path.expanduser('~').encode()
    leaked = [f for f in os.listdir(LINKED) if f.endswith('.dll') and home in open(os.path.join(LINKED, f), 'rb').read()]
    check(not leaked, 'no build-machine home path inside the bundled (trimmed) assemblies'
          + (f' ({", ".join(leaked)})' if leaked else ''))
    lines.append('')

    lines += ['## Managed members after trimming (inspect-managed-members)', '']
    for key, label in (('members_core', 'ReC.Core.dll'), ('members_win', 'ReC.dll (ReC.Win)')):
        r = res[key]
        if '_error' in r or 'code' in r:
            lines.append(f'- {label}: error {r.get("message", r.get("_error"))}')
            fails.append(f'{label} members')
            continue
        counts = {k: v for k, v in walk(nr(r)) if isinstance(v, int) and k.count('.') <= 2 and 'count' in k.lower()}
        lines.append(f'- {label}: ' + (', '.join(f'{k}={v}' for k, v in list(counts.items())[:8]) or 'see JSON'))
    lines.append('- tag check: `python3 tools/cs_rea_members.py` (every `// js:` member found in the trimmed builds)')
    lines.append('')
    lines.append(f'Result: {"all expectations hold" if not fails else str(len(fails)) + " expectation(s) failed"}.')
    with open(os.path.join(OUT, 'summary.md'), 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print('\n'.join(ln for ln in lines if 'FAIL' in ln or ln.startswith('Result')))
    return 1 if fails else 0


def main(argv):
    exe = os.path.join(ROOT, 'dist', 'ReC.exe')
    if '--exe' in argv:
        exe = os.path.abspath(argv[argv.index('--exe') + 1])
    os.makedirs(OUT, exist_ok=True)
    res = {}
    for name, args in runs(exe).items():
        path = os.path.join(OUT, name + '.json')
        if '--no-run' not in argv:
            if '--evidence_output' in args:              # rea refuses to overwrite an Evidence file
                ev = args[args.index('--evidence_output') + 1]
                os.makedirs(os.path.dirname(ev), exist_ok=True)
                if os.path.exists(ev):
                    os.remove(ev)
            res[name] = rea(args)
            with open(path, 'w') as f:
                json.dump(scrub(res[name]), f, indent=1, sort_keys=True)
        else:
            res[name] = json.load(open(path))
        print(f'{name:14s} {"ERROR " + res[name]["_error"] if "_error" in res[name] else "ok"}')
    return summarize(exe, res)


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
